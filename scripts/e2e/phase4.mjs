// End-to-end API test for phase 4 (clients, gigs, gig routines, checklist, views).
// Usage: same as phase2.mjs (needs SUPABASE_SERVICE_ROLE_KEY in the environment).
import { createClient } from '@supabase/supabase-js'

const url = process.env.VITE_SUPABASE_URL
const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } })
const sb = createClient(url, process.env.VITE_SUPABASE_ANON_KEY, { auth: { persistSession: false } })
let failures = 0
const check = (label, cond, extra = '') => {
  if (!cond) failures++
  console.log(cond ? 'ok  ' : 'FAIL', label, cond ? '' : extra ?? '')
}
let userId
try {
  const email = `e2e-${Date.now()}@example.com`
  const { data: created, error: ce } = await admin.auth.admin.createUser({ email, password: 'Test-password-123', email_confirm: true })
  if (ce) throw ce
  userId = created.user.id
  await sb.auth.signInWithPassword({ email, password: 'Test-password-123' })

  const { data: item } = await sb.from('inventory_items').insert({ item_name: 'Deck', quantity: 1, catalog_key: 'bicycle-red' }).select().single()
  const { data: trick } = await sb.from('tricks').insert({ name: 'Ambitious', duration_min: 5, other_props: 'Sharpie' }).select().single()
  await sb.from('trick_props').insert({ trick_id: trick.id, item_id: item.id, quantity_needed: 2 })
  const { data: routine } = await sb.from('routines').insert({ name: 'Walkaround' }).select().single()
  await sb.rpc('add_trick_to_routine', { p_routine_id: routine.id, p_trick_id: trick.id })

  const { data: client, error: cle } = await sb.from('clients').insert({ name: 'Jane Doe', company: 'Acme', email: 'jane@acme.com' }).select().single()
  check('insert client', !cle, cle?.message)

  const starts = new Date(Date.now() + 7 * 86400000).toISOString()
  const { data: gig, error: ge } = await sb
    .from('gigs')
    .insert({ title: 'Acme party', client_id: client.id, starts_at: starts, fee: 900, deposit_amount: 300, payment_status: 'deposit_paid', currency: 'EUR' })
    .select()
    .single()
  check('insert gig', !ge, ge?.message)

  const { error: gre } = await sb.from('gig_routines').insert([{ gig_id: gig.id, routine_id: routine.id, position: 0 }])
  check('link routine', !gre, gre?.message)

  const { data: checklist, error: cke } = await sb
    .from('gig_checklist_items')
    .select('*, item:inventory_items(id, item_name, quantity, stock_status, catalog_key)')
    .eq('gig_id', gig.id)
    .order('created_at')
  check('checklist generated by trigger', !cke && checklist.length === 2, cke?.message ?? JSON.stringify(checklist))
  const deck = checklist?.find((c) => c.item_id)
  check('checklist embeds inventory', deck?.item?.catalog_key === 'bicycle-red' && deck.quantity_needed === 2)

  await sb.from('gig_checklist_items').update({ is_checked: true }).eq('id', deck.id)
  await sb.from('gig_checklist_items').insert({ gig_id: gig.id, label: 'Business cards' })
  const { error: se } = await sb.rpc('sync_gig_checklist', { p_gig_id: gig.id })
  const { data: after } = await sb.from('gig_checklist_items').select('label, is_checked, source').eq('gig_id', gig.id)
  check('refresh keeps checks & manual items', !se && after.length === 3 && after.find((a) => a.label === 'Deck').is_checked, se?.message)

  const { data: ov, error: ove } = await sb.from('gigs_overview').select('*').single()
  check(
    'gigs_overview',
    !ove && ov.client_name === 'Jane Doe' && Number(ov.amount_received) === 300 && ov.checklist_total === 3 && ov.checklist_done === 1 && ov.has_stock_alert === true,
    ove?.message ?? JSON.stringify(ov),
  )

  const { data: detail, error: de } = await sb
    .from('gigs')
    .select('*, client:clients(id, name, company, email, phone), gig_routines(id, position, routine:routines(id, name, status, routine_tricks(id, trick:tricks(duration_min, status))))')
    .eq('id', gig.id)
    .order('position', { referencedTable: 'gig_routines' })
    .maybeSingle()
  check('gig detail embeds client & routines', !de && detail.client.name === 'Jane Doe' && detail.gig_routines[0].routine.routine_tricks[0].trick.duration_min === 5, de?.message)

  const { data: cd, error: cde } = await sb
    .from('clients')
    .select('*, gigs(id, title, starts_at, ends_at, fee, currency, payment_status, location)')
    .eq('id', client.id)
    .maybeSingle()
  check('client detail embeds gigs', !cde && cd.gigs.length === 1, cde?.message)

  const { data: co, error: coe } = await sb.from('clients_overview').select('*').single()
  check('clients_overview', !coe && co.gig_count === 1 && Number(co.total_fees) === 900 && co.next_gig_at, coe?.message)

  const { data: rd, error: rde } = await sb.from('routines').select('id, gig_routines(id, gig:gigs(id, title, starts_at, payment_status))').eq('id', routine.id).single()
  check('routine detail embeds gigs', !rde && rd.gig_routines[0].gig.title === 'Acme party', rde?.message)

  const { error: dle } = await sb.from('gig_routines').delete().eq('gig_id', gig.id)
  const { data: left } = await sb.from('gig_checklist_items').select('label').eq('gig_id', gig.id)
  check('unlink routine prunes auto items', !dle && left.length === 1 && left[0].label === 'Business cards', dle?.message)

  const { error: dge } = await sb.from('gigs').delete().eq('id', gig.id)
  check('delete gig', !dge, dge?.message)
} catch (e) {
  failures++
  console.log('FAIL exception', e.message)
} finally {
  if (userId) {
    const { error } = await admin.auth.admin.deleteUser(userId)
    console.log(error ? `FAIL cleanup ${error.message}` : 'ok   test user deleted')
  }
}
process.exit(failures ? 1 : 0)
